import { ProvisionHubFile } from './dto/provision.dto';

/** Public hub repo that holds the canonical compose (kept current by the mirror). */
const HUB_COMPOSE_URL =
  'https://raw.githubusercontent.com/Vahan132/restaurant-os-hub/main/docker-compose.edge.yml';

export interface HubBundleInput {
  organizationId: string;
  restaurantId: string;
  branchId: string;
  nodeId: string;
  nodeToken: string;
  /** Cloud API base (…/res/api). Empty string ⇒ left blank (point later). */
  cloudUrl?: string;
  dbPassword: string;
  jwtAccess: string;
  jwtRefresh: string;
  platformAccess: string;
  platformRefresh: string;
  consumerAccess: string;
  consumerRefresh: string;
  posDeviceSecret: string;
  kdsDeviceSecret: string;
}

/**
 * EDGE-OFFLINE-UI: build the self-contained hub bundle. A fully-filled `.env.edge`
 * (identity + node token + cloud URL + generated secrets + baked POS/KDS device
 * secrets — the operator edits NOTHING) plus a one-click run script per OS that
 * fetches the canonical compose and starts the stack. The hub boots ALREADY
 * PAIRED (ids + token baked) and self-provisions its devices, so every POS/KDS it
 * serves works with no enrollment.
 */
export function buildHubBundle(input: HubBundleInput): ProvisionHubFile[] {
  const envEdge = [
    '# Restaurant OS — edge hub (generated by the dashboard; do not edit by hand).',
    'APP_MODE=EDGE',
    'NODE_ENV=production',
    'PORT=3001',
    '',
    '# Images',
    'EDGE_IMAGE_TAG=latest',
    'EDGE_UI_TAG=develop',
    'HTTP_PORT=80',
    '',
    '# Identity (this hub is pre-paired — delivered by the dashboard).',
    `EDGE_ORG_ID=${input.organizationId}`,
    `EDGE_RESTAURANT_ID=${input.restaurantId}`,
    `EDGE_BRANCH_ID=${input.branchId}`,
    `EDGE_NODE_ID=${input.nodeId}`,
    `EDGE_NODE_TOKEN=${input.nodeToken}`,
    `CLOUD_URL=${input.cloudUrl ?? ''}`,
    '',
    '# Local database',
    'EDGE_DB_USER=restaurantos',
    `EDGE_DB_PASSWORD=${input.dbPassword}`,
    'EDGE_DB_NAME=restaurantos',
    '',
    '# Auth secrets (per-hub; independent of the cloud).',
    `JWT_ACCESS_SECRET=${input.jwtAccess}`,
    `JWT_REFRESH_SECRET=${input.jwtRefresh}`,
    `PLATFORM_JWT_ACCESS_SECRET=${input.platformAccess}`,
    `PLATFORM_JWT_REFRESH_SECRET=${input.platformRefresh}`,
    `CONSUMER_JWT_ACCESS_SECRET=${input.consumerAccess}`,
    `CONSUMER_JWT_REFRESH_SECRET=${input.consumerRefresh}`,
    '',
    '# Hub-vouched devices — every POS/KDS the hub serves uses these, no enrollment.',
    `EDGE_POS_DEVICE_SECRET=${input.posDeviceSecret}`,
    `EDGE_KDS_DEVICE_SECRET=${input.kdsDeviceSecret}`,
    '',
    '# Fiscal is configured per restaurant in the dashboard — nothing to set here.',
    'FISCAL_CONFIG_BACKEND=FILE',
    '',
    '# Media + misc',
    'STORAGE_DRIVER=dev',
    'MEDIA_DEV_DIR=/data/media',
    'STORAGE_PUBLIC_BASE_URL=http://localhost:3001',
    'CORS_ORIGINS=*',
    'PLATFORM_ROOT_DOMAIN=edge.local',
    'TRUST_PROXY=1',
    'PIN_MAX_ATTEMPTS=500',
    'PIN_LOCKOUT_MINUTES=1',
    'EDGE_SEED=false',
    '',
  ].join('\n');

  const runCmd = [
    '@echo off',
    'setlocal',
    'cd /d "%~dp0"',
    'echo Restaurant OS hub - starting...',
    'where docker >nul 2>nul || (echo Docker Desktop is required. Install it, start it, then run this again. ^& pause ^& exit /b 1)',
    'echo Downloading configuration...',
    `curl -fsSL -o docker-compose.edge.yml ${HUB_COMPOSE_URL} || (echo Could not download. Check the internet connection. ^& pause ^& exit /b 1)`,
    'echo Starting (the first run downloads images; this can take a few minutes)...',
    'docker compose -f docker-compose.edge.yml --env-file .env.edge up -d || (echo Start failed. See the message above. ^& pause ^& exit /b 1)',
    'echo.',
    'echo Done. On this computer the apps are at:',
    'echo    POS:   http://localhost/res/pos',
    'echo    KDS:   http://localhost/res/kds',
    'echo    Admin: http://localhost/res/admin',
    'pause',
    '',
  ].join('\r\n');

  const runSh = [
    '#!/usr/bin/env bash',
    'set -e',
    'cd "$(dirname "$0")"',
    'command -v docker >/dev/null 2>&1 || { echo "Docker is required. Install it and run this again."; exit 1; }',
    'echo "Downloading configuration..."',
    `curl -fsSL -o docker-compose.edge.yml ${HUB_COMPOSE_URL}`,
    'echo "Starting (first run downloads images; this can take a few minutes)..."',
    'docker compose -f docker-compose.edge.yml --env-file .env.edge up -d',
    'echo "Done. Apps: http://localhost/res/pos  (KDS: /res/kds, Admin: /res/admin)"',
    '',
  ].join('\n');

  return [
    { path: '.env.edge', content: envEdge },
    { path: 'run.cmd', content: runCmd },
    { path: 'run.sh', content: runSh },
  ];
}
